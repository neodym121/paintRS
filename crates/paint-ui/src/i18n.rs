//! Interface strings (own wording, RU + EN).

use serde::{Deserialize, Serialize};

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum Lang {
    #[default]
    Ru,
    En,
}

impl Lang {
    pub fn tr(self) -> &'static Tr {
        match self {
            Lang::Ru => &RU,
            Lang::En => &EN,
        }
    }
}

