"""Subset the Lucide icon font to the icons PaintRS uses and generate icons.rs.

Usage: python tools/icons/build_icons.py <lucide-static package dir>
Needs fontTools (pip install fonttools). Lucide is ISC-licensed (see THIRD_PARTY.md).
"""
import json
import pathlib
import sys

from fontTools import subset

root = pathlib.Path(__file__).resolve().parents[2]
pkg = pathlib.Path(sys.argv[1])
codepoints = json.loads((pkg / "font" / "codepoints.json").read_text(encoding="utf-8"))
names = []
for line in (root / "tools" / "icons" / "icons.txt").read_text(encoding="utf-8").splitlines():
    if line.strip().startswith("#"):
        continue
    names += line.split()
names = sorted(set(names))
missing = [n for n in names if n not in codepoints]
if missing:
    sys.exit(f"unknown icons: {missing}")

out_font = root / "crates" / "paint-ui" / "assets" / "fonts" / "lucide-subset.ttf"
opts = subset.Options()
opts.layout_features = []
opts.name_IDs = ["*"]
opts.notdef_outline = True
font = subset.load_font(str(pkg / "font" / "lucide.ttf"), opts)
sub = subset.Subsetter(opts)
sub.populate(unicodes=[codepoints[n] for n in names])
sub.subset(font)
subset.save_font(font, str(out_font), opts)

lines = [
    "//! Lucide icon codepoints (generated by tools/icons/build_icons.py — do not edit by hand).",
    "",
]
for n in names:
    const = n.upper().replace("-", "_")
    escape = "\\u{" + f"{codepoints[n]:X}" + "}"
    lines.append(f"pub const {const}: char = '{escape}';")
(root / "crates" / "paint-ui" / "src" / "icons.rs").write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"{len(names)} icons, font {out_font.stat().st_size} bytes")
